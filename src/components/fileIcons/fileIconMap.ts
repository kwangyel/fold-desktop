function normalizeName(name: string): string {
  return name.toLowerCase();
}

export function resolveFileIconKind(
  name: string,
  isFolder = false,
  isExpanded = false,
): FileIconKind {
  const normalized = normalizeName(name);

  if (isFolder) {
    if (isExpanded) return "folder-open";
    return FOLDER_NAME_MAP[normalized] ?? "folder";
  }

  const byName = FILE_NAME_MAP[normalized];
  if (byName) return byName;

  const dotIndex = normalized.lastIndexOf(".");
  if (dotIndex > 0) {
    const ext = normalized.slice(dotIndex + 1);
    const byExt = EXTENSION_MAP[ext];
    if (byExt) return byExt;
  }

  return "file";
}
