function shuffle<T>(items: T[]): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/**
 * Pick a unique place-style name not already used by existing worktrees.
 * Falls back to `name-<n>` if the pool is exhausted.
 */
export function pickWorktreeName(existing: string[]): string {
  const taken = new Set(existing.map((n) => n.toLowerCase()));
  for (const name of shuffle(PLACE_NAMES)) {
    if (!taken.has(name)) return name;
  }
  let n = 2;
  while (taken.has(`workspace-${n}`)) n += 1;
  return `workspace-${n}`;
}
